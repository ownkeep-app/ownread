import 'dart:ui' show Color;

/// App theme colour presets (「主题颜色」). Muted tones that sit well on the
/// warm paper background in both light and dark mode.
enum ThemeAccent {
  orange(Color(0xFFE07A3D), '暖橙'),
  vermilion(Color(0xFFD9554A), '朱红'),
  rose(Color(0xFFD35F8D), '玫瑰'),
  violet(Color(0xFF8A6FCB), '紫藤'),
  indigo(Color(0xFF4F7FD8), '靛蓝'),
  teal(Color(0xFF2C9A90), '青碧'),
  bamboo(Color(0xFF5E9A4C), '竹绿'),
  graphite(Color(0xFF6E7681), '墨灰');

  const ThemeAccent(this.color, this.label);

  final Color color;
  final String label;

  static ThemeAccent fromName(String? name) => ThemeAccent.values.firstWhere(
        (a) => a.name == name,
        orElse: () => ReadingSettings.defaultAccent,
      );
}

/// Reading page backgrounds (「阅读背景」). Each design has a light and a dark
/// tile in `assets/backgrounds/` (generated by `tool/gen_backgrounds.swift`);
/// [plain] is the flat paper colour.
enum ReadingBackground {
  plain('纯色', Color(0xFFF7F1E7), Color(0xFF1A1816)),
  xuan('宣纸', Color(0xFFF6EEE0), Color(0xFF1C1916)),
  bamboo('竹影', Color(0xFFEAF0DF), Color(0xFF151A15)),
  wave('海波', Color(0xFFE6EFEE), Color(0xFF121A1B)),
  stars('星河', Color(0xFFEEECF5), Color(0xFF13131E)),
  sakura('樱落', Color(0xFFF7E8E9), Color(0xFF1D1517));

  const ReadingBackground(this.label, this.lightBase, this.darkBase);

  final String label;

  /// The tile's base colour, used while the image loads and for flat areas.
  final Color lightBase;
  final Color darkBase;

  Color base(bool dark) => dark ? darkBase : lightBase;

  /// Tile asset, or null for [plain].
  String? asset(bool dark) => this == ReadingBackground.plain
      ? null
      : 'assets/backgrounds/${name}_${dark ? 'dark' : 'light'}.jpg';

  static ReadingBackground fromName(String? name) =>
      ReadingBackground.values.firstWhere(
        (b) => b.name == name,
        orElse: () => ReadingSettings.defaultBackground,
      );
}

/// Bundled reading typefaces (files under `assets/fonts/`, see pubspec).
enum ReadingFont {
  notoSans('NotoSansSC', '思源黑体'),
  harmonySans('HarmonyOSSansSC', '鸿蒙黑体'),
  yuan975('LXGW975YuanSC', '霞鹜975圆体'),
  chillRound('ChillRoundF', '寒蝉全圆体'),
  fangYuan('AlimamaFangYuanTi', '阿里妈妈方圆体');

  const ReadingFont(this.family, this.label);

  /// Family name declared in pubspec.yaml.
  final String family;

  /// Name shown in the settings picker.
  final String label;

  static ReadingFont fromName(String? name) => ReadingFont.values.firstWhere(
        (f) => f.name == name,
        orElse: () => ReadingSettings.defaultFont,
      );
}

/// Global reading appearance settings (persisted in SharedPreferences).
class ReadingSettings {
  const ReadingSettings({
    this.darkMode = false,
    this.fontSize = 18,
    this.lineHeight = 1.7,
    this.font = defaultFont,
    this.accent = defaultAccent,
    this.background = defaultBackground,
  });

  final bool darkMode;

  /// Font size in logical pixels.
  final double fontSize;

  final double lineHeight;

  /// Typeface for all text in the app.
  final ReadingFont font;

  /// Theme colour for buttons, highlights, progress and accents app-wide.
  final ThemeAccent accent;

  /// Background of the reading page (and editor).
  final ReadingBackground background;

  static const minFontSize = 14.0;
  static const maxFontSize = 32.0;
  static const minLineHeight = 1.2;
  static const maxLineHeight = 2.4;
  static const defaultFont = ReadingFont.chillRound;
  static const defaultAccent = ThemeAccent.orange;
  static const defaultBackground = ReadingBackground.xuan;

  /// Used for any glyph the chosen font lacks.
  static const fontFamilyFallbacks = <String>[
    'Microsoft YaHei',
    'PingFang SC',
    'Noto Sans CJK SC',
    'Source Han Sans SC',
    'sans-serif',
  ];

  String get fontFamily => font.family;

  ReadingSettings copyWith({
    bool? darkMode,
    double? fontSize,
    double? lineHeight,
    ReadingFont? font,
    ThemeAccent? accent,
    ReadingBackground? background,
  }) {
    return ReadingSettings(
      darkMode: darkMode ?? this.darkMode,
      fontSize: (fontSize ?? this.fontSize).clamp(minFontSize, maxFontSize),
      lineHeight:
          (lineHeight ?? this.lineHeight).clamp(minLineHeight, maxLineHeight),
      font: font ?? this.font,
      accent: accent ?? this.accent,
      background: background ?? this.background,
    );
  }

  Map<String, dynamic> toJson() => {
        'darkMode': darkMode,
        'fontSize': fontSize,
        'lineHeight': lineHeight,
        'font': font.name,
        'accent': accent.name,
        'background': background.name,
      };

  factory ReadingSettings.fromJson(Map<String, dynamic> json) {
    return ReadingSettings(
      darkMode: json['darkMode'] as bool? ?? false,
      fontSize: (json['fontSize'] as num?)?.toDouble() ?? 18,
      lineHeight: (json['lineHeight'] as num?)?.toDouble() ?? 1.7,
      font: ReadingFont.fromName(json['font'] as String?),
      accent: ThemeAccent.fromName(json['accent'] as String?),
      background: ReadingBackground.fromName(json['background'] as String?),
    );
  }

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is ReadingSettings &&
          darkMode == other.darkMode &&
          fontSize == other.fontSize &&
          lineHeight == other.lineHeight &&
          font == other.font &&
          accent == other.accent &&
          background == other.background;

  @override
  int get hashCode => Object.hash(
        darkMode,
        fontSize,
        lineHeight,
        font,
        accent,
        background,
      );
}
